/// Application opacity constants for consistent transparency values.
///
/// Based on Material Design emphasis levels.
abstract final class AppOpacity {
  /// Opacity for disabled / inactive elements.
  static const double disabled = 0.38;

  /// Medium-emphasis opacity (secondary text, icons).
  static const double medium = 0.5;

  /// High-emphasis opacity (primary text, active elements).
  static const double high = 0.87;

  /// Opacity for selected chip / tab backgrounds.
  static const double selectedChip = 0.15;

  /// Starting opacity for the price-flash highlight animation.
  static const double flashHighlight = 0.15;
}
